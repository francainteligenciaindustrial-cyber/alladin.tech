/* Tradução do SQL do sistema (dialeto SQLite) para o Postgres do Supabase.
 *
 * O sistema foi escrito em SQLite. Em vez de reescrever as ~520 consultas, cada uma
 * passa por aqui antes de ir ao Supabase:
 *   ?            → $1, $2…           LIKE → ILIKE (no SQLite LIKE ignora maiúsculas)
 *   date()/datetime()/strftime()/json_extract() → funções equivalentes criadas no banco (SQLITE_FUNCS)
 *   INSERT OR IGNORE → ON CONFLICT DO NOTHING
 *   INTEGER PRIMARY KEY AUTOINCREMENT → identidade do Postgres; REAL → DOUBLE PRECISION
 *   PRAGMA table_info / sqlite_master → information_schema
 */

// divide o SQL em trechos: código, 'texto', "identificador" e comentários (só o código é traduzido)
function tokens(sql) {
  const out = []; let i = 0, code = '';
  const flush = () => { if (code) { out.push({ t: 'code', v: code }); code = ''; } };
  while (i < sql.length) {
    const ch = sql[i];
    if (ch === "'" || ch === '"') {
      let j = i + 1;
      for (;;) { if (j >= sql.length) break; if (sql[j] === ch) { if (sql[j + 1] === ch) { j += 2; continue; } break; } j++; }
      flush(); out.push({ t: ch === "'" ? 'str' : 'ident', v: sql.slice(i, j + 1) }); i = j + 1; continue;
    }
    if (ch === '-' && sql[i + 1] === '-') { const j = sql.indexOf('\n', i); const end = j < 0 ? sql.length : j; flush(); i = end; continue; }
    if (ch === '/' && sql[i + 1] === '*') { const j = sql.indexOf('*/', i + 2); const end = j < 0 ? sql.length : j + 2; flush(); i = end; continue; }
    code += ch; i++;
  }
  flush();
  return out;
}

// separa vários comandos (para db.exec com vários CREATE TABLE etc.)
function splitStatements(sql) {
  const stmts = []; let cur = [];
  for (const tk of tokens(sql)) {
    if (tk.t !== 'code' || !tk.v.includes(';')) { cur.push(tk); continue; }
    const parts = tk.v.split(';');
    parts.forEach((p, k) => { if (p) cur.push({ t: 'code', v: p }); if (k < parts.length - 1) { stmts.push(cur); cur = []; } });
  }
  stmts.push(cur);
  return stmts.filter((s) => s.some((tk) => tk.t !== 'code' || tk.v.trim()));
}

const join = (tks) => tks.map((tk) => tk.v).join('');
const KEY_INT = /^(id|\w+_id)$/i; // chaves e referências viram BIGINT; demais inteiros viram DOUBLE PRECISION (o SQLite aceita 2.5 em INTEGER)

function ddlTypes(code) {
  return code
    .replace(/\bINTEGER\s+PRIMARY\s+KEY(\s+AUTOINCREMENT)?/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\b(\w+)\s+INTEGER\b/gi, (m, col) => /^(BIGINT|AS)$/i.test(col) ? m : `${col} ${KEY_INT.test(col) ? 'BIGINT' : 'DOUBLE PRECISION'}`)
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/\bBLOB\b/gi, 'BYTEA');
}

// traduz UM comando; devolve { sql, table, insert, params }
function translateOne(tks, counter) {
  const head = join(tks.filter((tk) => tk.t === 'code')).trim();
  // PRAGMA table_info(x) → colunas da tabela
  const pi = /^PRAGMA\s+table_info\s*\(\s*"?(\w+)"?\s*\)/i.exec(head);
  if (pi) return { sql: `SELECT column_name AS name, data_type AS type FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '${pi[1].toLowerCase()}' ORDER BY ordinal_position` };
  if (/^PRAGMA\b/i.test(head)) return null; // ajustes do SQLite: ignorados
  if (/^VACUUM\b/i.test(head)) return null;

  const isDDL = /^(CREATE\s+TABLE|ALTER\s+TABLE)\b/i.test(head);
  let orIgnore = false;
  const out = tks.map((tk) => {
    if (tk.t !== 'code') return tk.v;
    let v = tk.v;
    if (/\bINSERT\s+OR\s+IGNORE\s+INTO\b/i.test(v)) { orIgnore = true; v = v.replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/i, 'INSERT INTO'); }
    v = v.replace(/\bINSERT\s+OR\s+REPLACE\s+INTO\b/gi, 'INSERT INTO');
    if (isDDL) v = ddlTypes(v);
    v = v
      .replace(/\?/g, () => '$' + (++counter.n))
      // parâmetro sozinho em "? IS NULL" não tem tipo definido no Postgres
      .replace(/(\$\d+)(\s+IS\s+(NOT\s+)?NULL)/gi, '$1::text$2')
      .replace(/(^|[^\w.$])(NOT\s+)?LIKE\b/gi, (m, pre, not) => pre + (not || '') + 'ILIKE')
      .replace(/(^|[^\w.$"])(date|datetime|strftime|json_extract)\s*\(/gi, (m, pre, fn) => `${pre}sqlite_${fn.toLowerCase()}(`)
      .replace(/\bsqlite_master\b/gi, "(SELECT table_name::text AS name, 'table'::text AS type, ''::text AS sql FROM information_schema.tables WHERE table_schema = current_schema() AND table_type = 'BASE TABLE') AS sqlite_master")
      // apelidos com maiúsculas (ex.: totalSold) precisam de aspas para não virarem minúsculas
      .replace(/(^|[^\w$"])([a-z_][a-z0-9_]*[A-Z][A-Za-z0-9_]*)\b(?!\s*\()/g, (m, pre, id) => `${pre}"${id}"`);
    return v;
  });
  let sql = scalarMinMax(out.join('').trim());
  const ins = /^INSERT\s+INTO\s+"?(\w+)"?/i.exec(sql);
  if (orIgnore) sql += ' ON CONFLICT DO NOTHING';
  return { sql, insert: ins ? ins[1].toLowerCase() : null };
}

// MAX(a, b) / MIN(a, b) com 2+ valores (no SQLite é o maior/menor entre eles) → GREATEST / LEAST
function scalarMinMax(sql) {
  const re = /\b(MAX|MIN)\s*\(/gi; let m, res = '', last = 0;
  const inStr = (pos) => { let q = null; for (let i = 0; i < pos; i++) { const ch = sql[i]; if (q) { if (ch === q) q = null; } else if (ch === "'" || ch === '"') q = ch; } return !!q; };
  while ((m = re.exec(sql))) {
    if (inStr(m.index)) continue;
    let depth = 1, i = re.lastIndex, q = null, commas = 0;
    for (; i < sql.length && depth; i++) {
      const ch = sql[i];
      if (q) { if (ch === q) q = null; continue; }
      if (ch === "'" || ch === '"') q = ch;
      else if (ch === '(') depth++;
      else if (ch === ')') depth--;
      else if (ch === ',' && depth === 1) commas++;
    }
    if (commas) { res += sql.slice(last, m.index) + (m[1].toUpperCase() === 'MAX' ? 'GREATEST(' : 'LEAST('); last = re.lastIndex; }
  }
  return res + sql.slice(last);
}

const cache = new Map();
// para consultas com parâmetros (um comando só)
function translate(sql) {
  let r = cache.get(sql);
  if (r) return r;
  const stmts = splitStatements(sql);
  const counter = { n: 0 };
  r = translateOne(stmts[0] || [], counter) || { sql: '' };
  if (cache.size > 3000) cache.clear();
  cache.set(sql, r);
  return r;
}
// para db.exec (vários comandos, sem parâmetros)
function translateScript(sql) {
  return splitStatements(sql).map((s) => translateOne(s, { n: 0 })).filter((x) => x && x.sql);
}

// funções do SQLite recriadas no Postgres. offset = fuso da loja (ex.: '-4 hours' = Cuiabá)
const SQLITE_FUNCS = (offset) => `
CREATE OR REPLACE FUNCTION sqlite_ts(a text[]) RETURNS timestamp LANGUAGE plpgsql STABLE AS $f$
DECLARE t timestamp; m text;
BEGIN
  IF a IS NULL OR a[1] IS NULL OR a[1] = '' THEN RETURN NULL; END IF;
  IF lower(a[1]) = 'now' THEN t := (now() AT TIME ZONE 'UTC');
  ELSE BEGIN t := replace(a[1], 'T', ' ')::timestamp; EXCEPTION WHEN others THEN RETURN NULL; END;
  END IF;
  FOR i IN 2 .. coalesce(array_length(a, 1), 1) LOOP
    m := lower(trim(coalesce(a[i], '')));
    IF m = 'localtime' THEN t := t + interval '${offset}';
    ELSIF m = 'utc' THEN t := t - interval '${offset}';
    ELSIF m = 'start of day' THEN t := date_trunc('day', t);
    ELSIF m = 'start of month' THEN t := date_trunc('month', t);
    ELSIF m = 'start of year' THEN t := date_trunc('year', t);
    ELSIF m ~ '^[+-]?\\s*[0-9]+(\\.[0-9]+)?\\s+(second|minute|hour|day|month|year)s?$' THEN t := t + m::interval;
    END IF;
  END LOOP;
  RETURN t;
END $f$;
CREATE OR REPLACE FUNCTION sqlite_datetime(VARIADIC a text[]) RETURNS text LANGUAGE sql STABLE AS $f$ SELECT to_char(sqlite_ts(a), 'YYYY-MM-DD HH24:MI:SS') $f$;
CREATE OR REPLACE FUNCTION sqlite_date(VARIADIC a text[]) RETURNS text LANGUAGE sql STABLE AS $f$ SELECT to_char(sqlite_ts(a), 'YYYY-MM-DD') $f$;
CREATE OR REPLACE FUNCTION sqlite_strftime(f text, VARIADIC a text[]) RETURNS text LANGUAGE plpgsql STABLE AS $f$
DECLARE t timestamp := sqlite_ts(a); r text := f;
BEGIN
  IF t IS NULL THEN RETURN NULL; END IF;
  r := replace(r, '%Y', to_char(t, 'YYYY')); r := replace(r, '%m', to_char(t, 'MM')); r := replace(r, '%d', to_char(t, 'DD'));
  r := replace(r, '%H', to_char(t, 'HH24')); r := replace(r, '%M', to_char(t, 'MI')); r := replace(r, '%S', to_char(t, 'SS'));
  r := replace(r, '%j', to_char(t, 'DDD')); r := replace(r, '%w', (extract(dow FROM t))::int::text);
  r := replace(r, '%s', floor(extract(epoch FROM t))::bigint::text); r := replace(r, '%%', '%');
  RETURN r;
END $f$;
CREATE OR REPLACE FUNCTION sqlite_json_extract(j text, p text) RETURNS text LANGUAGE plpgsql IMMUTABLE AS $f$
BEGIN RETURN (j::jsonb) #>> string_to_array(regexp_replace(p, '^\\$\\.?', ''), '.');
EXCEPTION WHEN others THEN RETURN NULL; END $f$;
CREATE OR REPLACE FUNCTION round(double precision, integer) RETURNS double precision LANGUAGE sql IMMUTABLE AS $f$ SELECT round($1::numeric, $2)::double precision $f$;
CREATE OR REPLACE FUNCTION sqlite_compat_v1() RETURNS int LANGUAGE sql IMMUTABLE AS $f$ SELECT 1 $f$;
`;

module.exports = { translate, translateScript, SQLITE_FUNCS, splitStatements, tokens };
